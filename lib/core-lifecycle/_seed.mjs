/**
 * The .gitignore lines that exclude the overlay links, one line per LINK that actually exists.
 *
 * Two decisions, both learned the hard way:
 *
 *   - Enumeration, not a `.agents/skills/*` glob. Git cannot tell an overlay link from a skill
 *     directory the workspace author wrote, so a glob would silently stop their own skills from ever
 *     being committed.
 *   - Keyed on what is a LINK here, not on what the core ships. When a workspace authors a skill whose
 *     name the core also ships, the workspace's real directory wins (ensureCoreSkillOverlay leaves it
 *     alone) — and listing that name would then make the author's own work uncommittable.
 *
 * The list lives inside the managed block, so it refreshes on every `core init` / `core update`.
 *
 * @param {string[]} linkNames - names under <workspace>/.agents/skills that are links into the core
 * @returns {string[]}
 */
export function coreSkillIgnoreLines(linkNames) {
  if (!linkNames.length) return [];
  return [
    '',
    '# Framework skills projected out of the mounted core as folder links (Rule 3). The core is the',
    '# source of truth for them, so committing a link would duplicate an already-pinned submodule.',
    '# Listed one by one, never globbed, and only where the entry really is a link — a skill YOU',
    '# author stays committable even when it shadows a core skill of the same name.',
    ...[...linkNames].sort().map((n) => `/.agents/skills/${n}`),
  ];
}

/**
 * An empty local-memory store, matching what `sidekicks memory rebuild` would produce.
 *
 * @returns {string}
 */
export function emptyMemoryIndex() {
  return `# Local memory

Committed decision store for this workspace. Write entries with \`sidekicks memory add\` — never by
hand. One line per entry below.
`;
}

/**
 * A minimal workspace package.json. It exists so \`node\` treats .mjs consistently and so the
 * workspace has a name; it declares NO dependencies, because the framework has none.
 *
 * @param {string} repoRoot
 * @returns {string}
 */
export function workspacePackageJson(repoRoot) {
  return JSON.stringify({
    name: basename(repoRoot).toLowerCase().replace(/[^a-z0-9._-]+/g, '-'),
    version: '0.1.0',
    private: true,
    type: 'module',
    engines: { node: '>=20' },
    scripts: {
      sidekicks: 'node bin/sidekicks',
    },
  }, null, 2) + '\n';
}

/**
 * Write `content` to `abs` only when the file does not exist yet (the User class).
 *
 * @param {string} abs
 * @param {string} content
 * @returns {boolean} true when written
 */
export function writeIfAbsent(abs, content) {
  if (existsSync(abs)) return false;
  mkdirp(join(abs, '..'));
  writeAtomic(abs, content);
  return true;
}

/**
 * Write `content` unconditionally (the System class), returning whether the bytes changed.
 *
 * @param {string} abs
 * @param {string} content
 * @returns {boolean} true when the file's content changed
 */
export function writeSystem(abs, content) {
  let before = null;
  try {
    before = readFileSync(abs, 'utf8');
  } catch { /* absent */ }
  if (before === content) return false;
  mkdirp(join(abs, '..'));
  writeAtomic(abs, content);
  return true;
}

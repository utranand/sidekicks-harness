// Safe configuration inventory shared by core forging and mounted-workspace setup.
//
// Only examples, framework settings and config/.gitignore may cross the publication
// boundary.  This makes the convention additive: a new `foo.example.yaml` ships
// without a publisher allow-list, while a source `foo.yaml` is never treated as a
// template value.

import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, sep, dirname } from 'node:path';
import { createHash } from 'node:crypto';

const CONFIG = join('.sidekicks', 'config');
const PROJECTION_STATE = join('.sidekicks', 'state', 'core-config-templates.json');
const EXAMPLE_RE = /\.example\.(ya?ml|json)$/i;
const DATA_RE = /\.(ya?ml|json)$/i;
const SECRET_RE = /\.secret\.ya?ml$/i;
const portable = (p) => p.split(sep).join('/');
const digest = (file) => createHash('sha256').update(readFileSync(file, 'utf8').replace(/\r\n/g, '\n'), 'utf8').digest('hex');

function walk(dir, rel = '') {
  if (!existsSync(dir)) return [];
  const rows = [];
  for (const ent of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const next = rel ? join(rel, ent.name) : ent.name;
    if (ent.isDirectory()) rows.push(...walk(join(dir, ent.name), next));
    else if (ent.isFile()) rows.push(next);
  }
  return rows;
}

/** Skill-owned family files are generated by `config sync`, not standalone templates. */
function skillFamilies(root) {
  const result = new Set();
  for (const base of [join(root, '.agents', 'skills'), join(root, '.sidekicks', 'skill-offloaded')]) {
    if (!existsSync(base)) continue;
    for (const ent of readdirSync(base, { withFileTypes: true })) {
      if (!ent.isDirectory()) continue;
      const descriptor = join(base, ent.name, 'skill.yaml');
      if (!existsSync(descriptor)) continue;
      const text = readFileSync(descriptor, 'utf8');
      for (const match of text.matchAll(/^\s*family:\s*([A-Za-z0-9_.-]+)\s*$/gm)) result.add(match[1]);
    }
  }
  return result;
}

/**
 * Deterministic, safe configuration inventory. Included rows have a source hash;
 * excluded rows deliberately do not, so a credential cannot leak via metadata.
 */
export function configurationInventory(root) {
  const configDir = join(root, CONFIG);
  const families = skillFamilies(root);
  const rows = [];
  const files = walk(configDir);
  const examples = new Set(files.filter((rel) => EXAMPLE_RE.test(rel))
    .map((rel) => rel.replace(/\.example(?=\.(?:ya?ml|json)$)/i, '')));
  for (const rel of files) {
    const source = join(configDir, rel);
    const destination = portable(join(CONFIG, rel));
    if (SECRET_RE.test(rel) || /(^|\/)pending-removal\./i.test(rel)
      || rel === 'settings.json' || /(^|\/)(state|artifacts)(\/|$)/.test(rel)) {
      rows.push({ source: portable(join(CONFIG, rel)), destination, classification: 'excluded', reason: 'secret, retired, or state file' });
      continue;
    }
    if (rel === '.gitignore') {
      rows.push({ source: portable(join(CONFIG, rel)), destination, classification: 'gitignore', initializer_origin: 'framework config ignore', mode: 'copy', hash: digest(source) });
      continue;
    }
    if (rel.startsWith(`settings${sep}`) && DATA_RE.test(rel)) {
      rows.push({ source: portable(join(CONFIG, rel)), destination, classification: 'settings', initializer_origin: 'framework setting', mode: 'copy', hash: digest(source) });
      continue;
    }
    if (EXAMPLE_RE.test(rel)) {
      const canonical = rel.replace(/\.example(?=\.(?:ya?ml|json)$)/i, '');
      rows.push({ source: portable(join(CONFIG, rel)), destination, classification: 'example', initializer_origin: 'example', mode: 'copy', hash: digest(source) });
      rows.push({ source: portable(join(CONFIG, rel)), destination: portable(join(CONFIG, canonical)), classification: 'template', initializer_origin: portable(join(CONFIG, rel)), mode: 'render', hash: digest(source) });
      continue;
    }
    if (DATA_RE.test(rel) && !rel.includes(sep)) {
      const stem = rel.replace(/\.(ya?ml|json)$/i, '');
      if (examples.has(rel)) {
        // The example row above owns this canonical destination; source values never travel.
        continue;
      } else if (families.has(stem)) {
        rows.push({ source: portable(join(CONFIG, rel)), destination, classification: 'skill-family', reason: 'generated by config sync' });
      } else {
        rows.push({ source: portable(join(CONFIG, rel)), destination, classification: 'missing-initializer', initializer_origin: portable(join(CONFIG, `${stem}.example${rel.slice(stem.length)}`)), reason: 'standalone configuration needs an adjacent .example file' });
      }
    }
  }
  return rows.sort((a, b) => a.destination.localeCompare(b.destination) || a.classification.localeCompare(b.classification));
}

/** Write only missing workspace configuration files; never overwrite user state. */
export function projectConfigurationTemplates(coreDir, workspaceRoot, { writeIfAbsent }) {
  const created = [], kept = [], obsolete = [];
  const inventory = configurationInventory(coreDir);
  const active = new Set(inventory.filter((row) => row.mode).map((row) => row.destination));
  for (const row of inventory) {
    if (!row.mode) continue;
    const src = join(coreDir, ...row.source.split('/'));
    const dst = join(workspaceRoot, ...row.destination.split('/'));
    if (writeIfAbsent(dst, readFileSync(src, 'utf8'))) created.push(row.destination);
    else kept.push(row.destination);
  }
  // Only paths this helper recorded during an earlier projection can become obsolete. Scanning all
  // workspace YAML/JSON would mislabel a user's own configuration as framework-owned.
  let previous = [];
  try { previous = JSON.parse(readFileSync(join(workspaceRoot, PROJECTION_STATE), 'utf8')).paths || []; } catch { /* first install */ }
  for (const candidate of previous) {
    if (!active.has(candidate) && existsSync(join(workspaceRoot, ...candidate.split('/')))) obsolete.push(candidate);
  }
  const statePath = join(workspaceRoot, PROJECTION_STATE);
  mkdirSync(dirname(statePath), { recursive: true });
  writeFileSync(statePath, `${JSON.stringify({ paths: [...active].sort() }, null, 2)}\n`, 'utf8');
  return { created: created.sort(), kept: kept.sort(), obsolete: obsolete.sort(), inventory };
}

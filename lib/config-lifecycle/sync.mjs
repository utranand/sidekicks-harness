// lib/config-lifecycle/sync.mjs
// `sidekicks config sync [--scope <name>] [--only a,b] [--dry-run] [--check] [--refresh] [--prune] [--json]`
//
// THE RESCAN VERB. It walks every installed skill's `config:` declaration — not a catalog — and
// makes sure each declared block is documented in the scope's family file, seeded from the skill's
// own `config.defaults.yaml`. Adding or enhancing a skill therefore changes what this generates
// with no list to maintain anywhere.
//
// It is the CONFIGURATION half of a pair. The SETTINGS half — the boolean enable map in
// `.sidekicks/config/settings/` — is `framework sync`, which this verb also runs at the end so one
// command leaves both halves complete. See docs/guide/settings-vs-configuration.md.
//
// GENERATED BLOCKS ARE COMMENTED OUT, AND THAT IS THE WHOLE SAFETY MODEL.
// Writing live default values into a scope's family file would make that file SHADOW the skill's
// defaults: the skill later improves a default, and the scope silently keeps the old value forever
// because a higher layer now carries it. Emitting the block inert means
//   - the file documents the schema, so a fresh clone can see what is configurable;
//   - the block still resolves to the OWNING SKILL's defaults until a human uncomments a key,
//     which is exactly the "fall back to the skill if not configured" contract;
//   - uncommenting is an explicit, reviewable override.
// This is the stance sk-hello's config-init.mjs took against the pre-family monolith. That
// script is retired and this verb replaced it: a structural write under `.sidekicks/` belongs to
// the CLI (Rule 1), not to a skill's bundled script, and a second implementation of the resolution
// chain living inside a skill is how that skill's audit came to report every configured connector
// in this repo as unconfigured.
//
// THREE ACTIONS, IN STRICT ORDER OF SAFETY:
//   add      the family file lacks the block entirely            → appended, inert
//   refresh  the block is present but VALUE-FREE (scaffold)      → regenerated; opt-in via --refresh
//   keep     the block carries live values                       → NEVER touched, in any mode.
//            Keys the current defaults document that the live block lacks are REPORTED as drift
//            for a human to merge. A live config may hold real credentials; rewriting it is not a
//            risk worth any convenience.
// Nothing is ever deleted. `--prune` MOVES an undeclared block to `pending-removal.<family>.yaml`
// (git-ignored) rather than dropping it.
//
// Zero npm dependencies — node:* + lib/ back-edges only.


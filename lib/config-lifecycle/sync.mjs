/** One block rendered as an inert, fully commented region. */
function renderInert(block, value) {
  const body = renderBody(value, 1);
  // A block whose defaults are deliberately empty (`confluence: {}` — keyed by an alias nobody can
  // guess) must still say so explicitly, the same way renderBody spells a nested empty mapping.
  // A bare `# confluence:` would read as a truncated block rather than an intentional one.
  if (!body.length) return [`# ${block}: {}`];
  // renderBody returns LINES, not a string — every one of them gets the comment marker, so the
  // whole region is inert and the file still parses as if the block were absent.
  const lines = [`# ${block}:`];
  for (const line of body) lines.push(line === '' ? '#' : `# ${line}`);
  return lines;
}

/**
 * Apply one scope's plan. One read-modify-write per family file, so a file is never seen
 * half-updated by anything else.
 */
function applyScope(repoRoot, plan, blocks, prune) {
  const byFile = new Map();
  for (const item of plan.items) {
    if (item.action !== 'add' && item.action !== 'refresh') continue;
    if (!byFile.has(item.file)) byFile.set(item.file, []);
    byFile.get(item.file).push(item);
  }

  const written = [];
  for (const [rel, items] of byFile) {
    const abs = join(repoRoot, rel);
    const exists = existsSync(abs);
    const before = exists ? readFileSync(abs, 'utf8') : '';
    const crlf = /\r\n/.test(before);
    // Normalise to LF for every mutation and convert back exactly once on write. Skipping the
    // read-side normalisation turns each existing \r\n into \r\r\n — corrupting the whole file on
    // the commonest path there is (an add-only run against a CRLF config).
    let lines = exists
      ? before.replace(/\r\n/g, '\n').replace(/\n$/, '').split('\n')
      : familyHeader(items[0].family, rel.split(/[\\/]/).pop());

    // Refresh first, bottom-up, so earlier line ranges stay valid as the array shifts.
    const refreshes = items
      .filter((i) => i.action === 'refresh')
      .map((i) => ({ item: i, region: commentedRegion(lines, i.block) }))
      .filter((r) => r.region !== null)
      .sort((a, b) => b.region.start - a.region.start);
    for (const r of refreshes) {
      lines.splice(
        r.region.start,
        r.region.end - r.region.start + 1,
        ...renderInert(r.item.block, r.item.seed)
      );
    }

    // A refresh whose region could not be located (a LIVE-but-value-free block, which has real
    // YAML lines rather than a comment region) is left for the human: rewriting real lines is the
    // one thing this verb never does.
    const adds = items.filter((i) => i.action === 'add');
    if (adds.length) {
      while (lines.length && lines[lines.length - 1].trim() === '') lines.pop();
      lines.push('', BANNER_RULE, `# ${BANNER_TEXT}`, '# Uncomment a key to override the skill\'s default.', BANNER_RULE);
      for (const item of adds) {
        lines.push('');
        lines.push(...renderInert(item.block, item.seed));
      }
    }

    const next = lines.join('\n') + '\n';
    const out = crlf ? next.replace(/\n/g, '\r\n') : next;
    if (out === before) continue;
    assertWritable(abs, repoRoot);
    writeAtomic(abs, out);
    written.push(rel);
  }

  // The git-ignored credential siblings: a skeleton of exactly the credential keys the defaults
  // document, so a fresh clone has somewhere obvious to put them.
  //
  // INERT, LIKE THE FAMILY FILE, AND FOR A SHARPER REASON. A LIVE `api_token: ""` here is a real
  // key in the ROOT-CONFIG group, and mergeGroups gives the first group carrying a key ownership of
  // it — so an empty placeholder would SHADOW whatever the owning skill's defaults say, and the
  // block's own source would read `root-config` when nothing was ever configured. Commented out, it
  // documents where the credential goes and changes nothing until `config set --secret` writes a
  // real one.
  const secrets = [];
  for (const item of plan.items) {
    // Any block the scope has not configured itself, not just the ones added on THIS run: a repo
    // whose family files were scaffolded before the credential skeleton existed would otherwise
    // never get one, because the block is no longer an `add`. `keep` is excluded — a scope that
    // carries live values manages its own credentials.
    if (!item.seed || item.action === 'keep') continue;
    const entry = blocks.find((b) => b.block === item.block);
    if (!entry) continue;
    const { secret } = splitSecrets(item.seed, entry.public_keys);
    if (!Object.keys(secret).length) continue;

    const secretRel = join(plan.base, CONFIG_DIR, entry.secret);
    const secretAbs = join(repoRoot, secretRel);
    const exists = existsSync(secretAbs);
    // Never rewrite a file that may hold a real credential, and never re-add a block it already
    // documents (live or commented).
    if (exists && blockStatus(repoRoot, secretRel, entry) !== 'absent') continue;

    const before = exists ? readFileSync(secretAbs, 'utf8') : '';
    const crlf = /\r\n/.test(before);
    const lines = exists
      ? before.replace(/\r\n/g, '\n').replace(/\n$/, '').split('\n')
      : [
        `# ${entry.secret} — CREDENTIALS ONLY, and GIT-IGNORED.`,
        '#',
        `# The committed '${entry.file}' beside this file carries the structure with every`,
        '# credential key present but empty; the values belong here. Uncomment a key and fill it in,',
        '# or let `sidekicks config set <block>.<key> <value> --secret` write it for you.',
      ];
    while (lines.length && lines[lines.length - 1].trim() === '') lines.pop();
    lines.push('');
    lines.push(...renderInert(item.block, secret));

    const next = lines.join('\n') + '\n';
    const out = crlf ? next.replace(/\n/g, '\r\n') : next;
    assertWritable(secretAbs, repoRoot);
    writeAtomic(secretAbs, out);
    secrets.push(secretRel);
  }
  if (written.length || secrets.length) {
    ensureSecretIgnore(repoRoot, join(plan.base, CONFIG_DIR));
  }

  // Prune: an undeclared block is MOVED to the parked file, never dropped. Its value may be the
  // only remaining record of how something was configured.
  const pruned = [];
  const orphansByFile = new Map();
  for (const orphan of (prune ? plan.orphans : [])) {
    if (!orphansByFile.has(orphan.file)) orphansByFile.set(orphan.file, []);
    orphansByFile.get(orphan.file).push(orphan);
  }
  for (const [rel, orphans] of orphansByFile) {
    const abs = join(repoRoot, rel);
    let text = readFileSync(abs, 'utf8');
    const name = rel.split(/[\\/]/).pop();
    const parkedRel = join(plan.base, CONFIG_DIR, `${PENDING_PREFIX}${name}`);
    for (const orphan of orphans) {
      const value = blockFromFile(abs, rel, orphan.block, []);
      if (value === null) continue;
      writeBlock(repoRoot, parkedRel, orphan.block, value, {
        header: [
          `# ${PENDING_PREFIX}${name} — blocks 'sidekicks config sync --prune' moved out of`,
          `# ${name} because no installed skill declares them any more. GIT-IGNORED.`,
          '#',
          '# Nothing reads this file. It exists so a value is never destroyed by a prune: restore a',
          '# block by declaring it again in the owning skill, then paste it back.',
        ],
      });
      text = removeBlock(text, orphan.block);
      pruned.push(orphan.block);
    }
    assertWritable(abs, repoRoot);
    writeAtomic(abs, text);
    ensurePendingIgnore(repoRoot, join(plan.base, CONFIG_DIR));
  }

  return { written, secrets, pruned };
}


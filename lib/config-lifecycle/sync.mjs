/**
 * Decide, without writing anything, what each declared block needs in one scope.
 *
 * @param {string} repoRoot
 * @param {{scope: string, base: string}} target
 * @param {Array<object>} blocks - the merged block registry
 * @param {{refresh: boolean, prune: boolean}} opts
 */
function planScope(repoRoot, target, blocks, opts) {
  const isRoot = target.base === '.sidekicks';
  const items = [];

  for (const entry of blocks) {
    // `--only` narrows the run to the blocks the user actually asked for.
    const named = !opts.only
      || opts.only.has(entry.block) || entry.aliases.some((a) => opts.only.has(a));
    if (!named) continue;

    // A root-scoped block is infrastructure the framework reads at root only — generating it into
    // a project would document a file nothing there will ever read. Naming it under `--only` does
    // not change that, but it does change the reporting: silence would read as "done", so the
    // block is listed as skipped with the reason. Asking for it is a mistake worth seeing.
    if (!isRoot && entry.scope === 'root') {
      if (opts.only) {
        items.push({
          block: entry.block, family: entry.family,
          file: join(target.base, CONFIG_DIR, entry.file), action: 'skip',
          why: 'root-scoped: the framework reads this block at root only, so documenting it in a '
            + 'project would describe a file nothing there reads — run with --scope root',
          missing: [], defaults_from: null,
        });
      }
      continue;
    }

    // The inverse, and it exists for the same reason: a project-scoped block is configured per
    // project, so generating it into the ROOT scope would document a file nothing will ever read
    // there -- and, worse, invite someone to fill it in where the resolver does not look. Reported
    // as skipped under `--only` so silence cannot read as "done".
    if (isRoot && entry.scope === 'project') {
      if (opts.only) {
        items.push({
          block: entry.block, family: entry.family,
          file: join(target.base, CONFIG_DIR, entry.file), action: 'skip',
          why: 'project-scoped: this block is configured per project, so documenting it at root '
            + 'would describe a file the resolver never reads -- run with --scope <project>',
          missing: [], defaults_from: null,
        });
      }
      continue;
    }

    const defaultsRel = entry.defaults_from
      ? join(entry.defaults_from.tree, entry.defaults_from.skill, entry.defaults_from.file)
      : null;
    const defaults = defaultsRel
      ? blockFromFile(join(repoRoot, defaultsRel), defaultsRel, entry.block, entry.aliases)
      : null;
    const seed = defaults ?? entry.builtin;

    const familyRel = join(target.base, CONFIG_DIR, entry.file);
    const status = blockStatus(repoRoot, familyRel, entry);

    if (!seed) {
      // Nothing to write. `defaults-missing` is the doctor's finding, not this verb's job; here it
      // is simply a block that cannot be seeded.
      items.push({
        block: entry.block, family: entry.family, file: familyRel, action: 'skip',
        why: 'the owning skill ships no config.defaults.yaml and declares no builtin',
        missing: [], defaults_from: defaultsRel,
      });
      continue;
    }

    if (status === 'live') {
      const live = blockFromFile(join(repoRoot, familyRel), familyRel, entry.block, entry.aliases);
      const missing = missingKeys(seed, live);
      items.push({
        block: entry.block, family: entry.family, file: familyRel, action: 'keep',
        // Not-overridden is NOT broken: an absent key resolves from the owning skill's defaults,
        // which is the contract. It is reported because the defaults may have grown keys worth
        // knowing about — a prompt to look, never a repair the verb should make.
        why: missing.length
          ? `carries live values — never rewritten; ${missing.length} key(s) the defaults `
            + 'document are not overridden here (they resolve from the skill)'
          : 'carries live values — never rewritten',
        missing, defaults_from: defaultsRel, seed,
      });
      continue;
    }

    if (status === 'scaffold') {
      items.push({
        block: entry.block, family: entry.family, file: familyRel,
        action: opts.refresh ? 'refresh' : 'skip',
        why: opts.refresh
          ? 'scaffold only (no live value) — regenerated from the current defaults'
          : 'scaffold already present — pass --refresh to regenerate it from the current defaults',
        missing: [], defaults_from: defaultsRel, seed, entry,
      });
      continue;
    }

    items.push({
      block: entry.block, family: entry.family, file: familyRel, action: 'add',
      why: 'declared by an installed skill, absent here',
      missing: [], defaults_from: defaultsRel, seed, entry,
    });
  }

  items.sort((a, b) => a.file.localeCompare(b.file) || a.block.localeCompare(b.block));
  // Orphans are found on EVERY run, not only under --prune: a block nothing declares any more is
  // worth naming the moment it is noticed. Only the acting on it is opt-in.
  //
  // A NARROWED run reports none. An orphan sweep is a statement about the whole scope, and making
  // it from a run that looked at four blocks would name as orphans the blocks the user simply did
  // not ask about.
  return { ...target, items, orphans: opts.only ? [] : findOrphans(repoRoot, target, blocks) };
}

/**
 * Top-level keys in a scope's family files that no registered block (or alias) claims.
 *
 * The legacy monolith is deliberately NOT scanned: `config migrate` owns that file, and a block
 * still sitting there is mid-migration, not an orphan.
 */
function findOrphans(repoRoot, target, blocks) {
  const claimed = new Set();
  for (const b of blocks) {
    claimed.add(b.block);
    for (const alias of b.aliases) claimed.add(alias);
  }
  const byFile = new Map();
  for (const b of blocks) byFile.set(b.file, b.family);

  const dirRel = join(target.base, CONFIG_DIR);
  const dirAbs = join(repoRoot, dirRel);
  if (!existsSync(dirAbs)) return [];
  let names = [];
  try { names = readdirSync(dirAbs); } catch { return []; }

  const out = [];
  for (const name of names) {
    // Only real family files: never a secret sibling, a parked monolith, or the settings directory.
    if (!name.endsWith('.yaml')) continue;
    if (name.endsWith('.secret.yaml') || name.startsWith(PENDING_PREFIX)) continue;
    if (!byFile.has(name)) continue;
    const rel = join(dirRel, name);
    let text = '';
    try { text = readFileSync(join(repoRoot, rel), 'utf8'); } catch { continue; }
    for (const { key } of topLevelKeyLines(text)) {
      if (claimed.has(key)) continue;
      out.push({ block: key, file: rel, family: byFile.get(name) });
    }
  }
  out.sort((a, b) => a.file.localeCompare(b.file) || a.block.localeCompare(b.block));
  return out;
}


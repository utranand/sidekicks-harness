/** Marker written above every generated region, and the way a later run recognises its own work. */
const BANNER_RULE = '#'.repeat(78);
const BANNER_TEXT = 'Generated by `sidekicks config sync` from the installed skills\' '
  + 'config.defaults.yaml.';

/** The header a family file this verb creates from scratch carries. */
function familyHeader(family, file) {
  return [
    `# ${file} — the '${family}' configuration family (COMMITTED).`,
    '#',
    '# CONFIGURATION, not settings: values. The boolean enable map lives in',
    '# .sidekicks/config/settings/. See docs/guide/settings-vs-configuration.md.',
    '#',
    '# Credentials NEVER live here. Every credential key appears with an empty value so a fresh',
    `# clone can see what to supply; the values go in the git-ignored '${family}.secret.yaml'`,
    '# sibling. Write with `sidekicks config set`, read with `sidekicks config get <block>`.',
    '#',
    '# A block that is present but entirely commented out is INERT: it documents the schema, and',
    '# the block still resolves to the owning skill\'s config.defaults.yaml until a key is',
    '# uncommented here.',
  ];
}

// ---------------------------------------------------------------------------
// Reading what a scope already has
// ---------------------------------------------------------------------------

/** Is every leaf of this value empty (''/null/{}/[])? Such a block decides nothing. */
function isValueFree(value) {
  if (value === null || value === undefined || value === '') return true;
  if (Array.isArray(value)) return value.every(isValueFree);
  if (typeof value === 'object') return Object.values(value).every(isValueFree);
  return false;
}

/**
 * A commented-out block this verb (or its predecessor) generated, located in the file's lines.
 *
 * The region starts at `# <block>:` in column 0 and runs while the following lines are comments
 * that are NOT another top-level `# <key>:` — i.e. the block's own indented body and any blank
 * comment lines inside it. A non-comment line ends it.
 *
 * @param {string[]} lines
 * @param {string} block
 * @returns {{start: number, end: number}|null} inclusive line indices
 */
function commentedRegion(lines, block) {
  const startRe = new RegExp(`^#\\s?${block}\\s*:`);
  const otherTop = /^#\s?[A-Za-z][A-Za-z0-9_-]*\s*:/;
  for (let i = 0; i < lines.length; i++) {
    if (!startRe.test(lines[i])) continue;
    let end = i;
    for (let j = i + 1; j < lines.length; j++) {
      const line = lines[j];
      if (!line.startsWith('#')) break;      // a real line ends the region
      if (otherTop.test(line)) break;        // the next generated block starts
      end = j;
    }
    return { start: i, end };
  }
  return null;
}

/**
 * What state a block is in inside one family file.
 *
 * @returns {'absent'|'scaffold'|'live'}
 */
function blockStatus(repoRoot, relPath, entry) {
  const abs = join(repoRoot, relPath);
  if (!existsSync(abs)) return 'absent';
  const live = blockFromFile(abs, relPath, entry.block, entry.aliases);
  if (live !== null) return isValueFree(live) ? 'scaffold' : 'live';
  const lines = readFileSync(abs, 'utf8').split(/\r?\n/);
  if (commentedRegion(lines, entry.block)) return 'scaffold';
  for (const alias of entry.aliases) {
    if (commentedRegion(lines, alias)) return 'scaffold';
  }
  return 'absent';
}

/** Dotted key paths a defaults value documents that a live block does not carry. */
function missingKeys(defaults, live, prefix = '') {
  const out = [];
  if (!defaults || typeof defaults !== 'object' || Array.isArray(defaults)) return out;
  for (const [key, value] of Object.entries(defaults)) {
    const path = prefix ? `${prefix}.${key}` : key;
    const has = live && typeof live === 'object' && !Array.isArray(live)
      && Object.prototype.hasOwnProperty.call(live, key);
    if (!has) { out.push(path); continue; }
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      out.push(...missingKeys(value, live[key], path));
    }
  }
  return out;
}


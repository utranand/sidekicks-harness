/**
 * Run `config sync`.
 *
 * @param {{ repoRoot: string, argv: string[], flags: object }} ctx
 * @param {object} _args - unused
 * @returns {Promise<{ stdout: string, exitCode: number }>}
 */
export async function run(ctx, _args) {
  const { repoRoot } = ctx;
  const flags = parseConfigFlags(ctx.argv, ['check', 'dry-run', 'refresh', 'prune', 'json']);
  const checkOnly = flags.check === true;
  // `--dry-run` and `--check` both write nothing, and they are NOT the same thing.
  //   --check    is the CI gate: it exits non-zero when a sync would close a gap.
  //   --dry-run  is the plan a human approves before it runs: same output, always exit 0.
  // Collapsing them would make the interactive walkthrough fail on the very state it exists to
  // report, which is how an approval step turns into an error nobody reads.
  const dryRun = flags['dry-run'] === true;
  const refresh = flags.refresh === true;
  const prune = flags.prune === true;
  const readOnly = checkOnly || dryRun;

  if (checkOnly && dryRun) {
    throw new SidekicksError(
      'config sync: --check and --dry-run both write nothing — use --check for the CI gate '
      + '(non-zero on a gap) or --dry-run for the plan (always exit 0), not both',
      EXIT_VALIDATION
    );
  }
  if (checkOnly && (refresh || prune)) {
    throw new SidekicksError(
      'config sync: --check writes nothing, so it cannot be combined with --refresh or --prune',
      EXIT_VALIDATION
    );
  }

  // `--only=jira,slack` narrows the run to named blocks. This is what makes the verb usable in a
  // guided first-time setup: a docs-only project may want two connectors and nothing else, and
  // documenting all thirty would bury the two it asked for.
  // PRESENT-BUT-EMPTY is an error, not "no narrowing". `--only=` reaching here as '' would
  // otherwise fall back to a full sync — the user asked to narrow and got the opposite, silently.
  const given = flags.only !== undefined;
  const only = given
    ? new Set(String(flags.only).split(',').map((s) => s.trim()).filter(Boolean))
    : null;
  if (only && !only.size) {
    throw new SidekicksError(
      "config sync: --only needs at least one block name, e.g. --only=jira,slack "
      + "(run 'sidekicks config list' to see them)",
      EXIT_USAGE
    );
  }

  const wanted = flags.scope ? String(flags.scope) : 'active';
  const targets = targetScopes(repoRoot, wanted);
  const { blocks } = buildFamilies(repoRoot);

  if (only) {
    const known = new Set(blocks.flatMap((b) => [b.block, ...b.aliases]));
    const unknown = [...only].filter((name) => !known.has(name));
    if (unknown.length) {
      throw new SidekicksError(
        `config sync: --only names ${unknown.length} block(s) nothing declares: ${unknown.join(', ')} `
        + "— run 'sidekicks config list' to see the declared blocks",
        EXIT_VALIDATION
      );
    }
  }

  const plans = targets.map((t) => planScope(repoRoot, t, blocks, { refresh, prune, only }));
  const applied = readOnly ? [] : plans.map((p) => applyScope(repoRoot, p, blocks, prune));

  // The SETTINGS half. One command leaves both halves of `config/` complete — except under
  // `--only`, which is a request about named CONFIGURATION blocks; materialising the enable map
  // there would write files the user did not ask about in a run they narrowed on purpose.
  const settings = readOnly || only
    ? frameworkDrift(repoRoot)
    : materializeFramework(repoRoot, { prune });

  const totals = { add: 0, refresh: 0, keep: 0, skip: 0, drift: 0, orphans: 0 };
  for (const plan of plans) {
    for (const item of plan.items) {
      totals[item.action] = (totals[item.action] ?? 0) + 1;
      if (item.missing.length) totals.drift += 1;
    }
    totals.orphans += plan.orphans.length;
  }

  // What FAILS --check is only what a command can fix: a declared block absent from the scope, or
  // a framework entry unlisted in the settings files. Drift inside a live block is a human merge —
  // failing CI on it would block on something no command may safely resolve.
  const drifted = totals.add > 0 || (checkOnly ? settings.missing.length > 0 : false);

  if (flags.json) {
    const payload = {
      ok: !drifted,
      checked: checkOnly,
      dry_run: dryRun,
      only: only ? [...only] : null,
      scopes: plans.map((p, i) => ({
        scope: p.scope,
        base: p.base,
        items: p.items.map((it) => ({
          block: it.block,
          family: it.family,
          file: it.file,
          action: it.action,
          why: it.why,
          missing_keys: it.missing,
          defaults_from: it.defaults_from,
        })),
        orphans: p.orphans,
        written: applied[i] ? applied[i].written : [],
        secrets: applied[i] ? applied[i].secrets : [],
        pruned: applied[i] ? applied[i].pruned : [],
      })),
      settings: (readOnly || only)
        ? { listed: settings.listed.length, toggleable: settings.toggleable, missing: settings.missing }
        : { added: settings.added, pruned: settings.pruned, path: settings.path },
      totals,
    };
    return {
      stdout: JSON.stringify(payload, null, 2) + '\n',
      exitCode: drifted && checkOnly ? EXIT_VALIDATION : EXIT_OK,
    };
  }

  const out = [];
  const SYMBOL = { add: '+', refresh: '~', keep: '=', skip: '.' };

  if (checkOnly) {
    if (!drifted) {
      out.push(`config sync --check: OK (${totals.keep} configured, ${totals.skip} documented, `
        + `${settings.listed.length}/${settings.toggleable} settings entries listed)`);
    } else {
      const lines = [];
      for (const plan of plans) {
        for (const item of plan.items) {
          if (item.action !== 'add') continue;
          lines.push(`  ${item.file}: '${item.block}' is declared by `
            + `${item.defaults_from ? item.defaults_from.split(/[\\/]/).slice(-2, -1)[0] : 'a skill'} `
            + 'but absent here');
        }
      }
      for (const id of settings.missing) lines.push(`  settings: '${id}' is not listed`);
      throw new SidekicksError(
        `config sync --check: ${lines.length} gap(s) a sync would close:\n${lines.join('\n')}\n`
        + "Run 'sidekicks config sync' to document them (blocks are written inert — they keep "
        + 'resolving to the owning skill\'s defaults until a key is uncommented).',
        EXIT_VALIDATION
      );
    }
    if (totals.drift) {
      out.push(`  note:    ${totals.drift} live block(s) do not override every key the current `
        + 'defaults document — run without --check to see which');
    }
    return { stdout: out.join('\n') + '\n', exitCode: EXIT_OK };
  }

  for (let i = 0; i < plans.length; i++) {
    const plan = plans[i];
    // A dry run applied nothing, so there is no result to render — the plan IS the output.
    const result = applied[i] || { written: [], secrets: [], pruned: [] };
    out.push(`config sync${dryRun ? ' --dry-run' : ''}: ${plan.scope} `
      + `(${join(plan.base, CONFIG_DIR)})`);
    for (const item of plan.items) {
      // Silence the already-correct on a full run — but never on a NARROWED one. `--only=jira`
      // that prints nothing reads as "found nothing", when it means "jira is configured and
      // healthy". The user named the block; answer about it.
      if (!only && item.action === 'keep' && !item.missing.length) continue;
      out.push(`  ${SYMBOL[item.action] ?? '?'} ${item.block.padEnd(28)} ${item.why}`);
      for (const key of item.missing) out.push(`      not overridden: ${key}`);
    }
    if (result.written.length) out.push(`  wrote:  ${result.written.join(', ')}`);
    if (result.secrets.length) out.push(`  seeded: ${result.secrets.join(', ')} (git-ignored)`);
    if (result.pruned.length) {
      out.push(`  parked: ${result.pruned.length} undeclared block(s) moved to `
        + `${PENDING_PREFIX}* — ${result.pruned.join(', ')}`);
    }
    if (plan.orphans.length && !prune) {
      out.push(`  NOTE: ${plan.orphans.length} block(s) here are declared by nothing `
        + `(${plan.orphans.map((o) => o.block).join(', ')}). Re-run with --prune to park them.`);
    }
  }

  if (dryRun) {
    out.push('');
    out.push('DRY RUN — nothing was written. Re-run without --dry-run to perform this plan.');
  } else if (only) {
    // A narrowed run deliberately leaves the settings half alone. Saying so beats a reader
    // assuming a plain `config sync` already happened.
    out.push(`settings: not touched — --only narrowed this run to `
      + `${[...only].join(', ')}; run 'sidekicks config sync' for the enable map`);
  } else {
    out.push(`settings: ${settings.added.length
      ? `listed ${settings.added.length} new entr(ies) in ${settings.path}`
      : 'already complete'}`);
  }
  if (!only && !dryRun && settings.unmigrated && settings.unmigrated.length) {
    out.push(`  NOTE: ${settings.unmigrated.length} id(s) still live only in the pre-split `
      + "monolith — 'sidekicks framework sync --split' moves them.");
  }

  return { stdout: out.join('\n') + '\n', exitCode: EXIT_OK };
}


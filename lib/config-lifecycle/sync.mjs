/**
 * Which scope bases this run targets.
 *
 * Unlike `config doctor`'s enumeration, `--scope all` includes a project that has NO configuration
 * yet: seeding the scope that lacks everything is the point of the verb, so filtering on "already
 * has a config/ directory" would skip exactly the case worth running.
 *
 * @param {string} repoRoot
 * @param {string} wanted - 'active' | 'root' | 'all' | a project name
 * @returns {Array<{scope: string, base: string}>}
 */
function targetScopes(repoRoot, wanted) {
  const root = { scope: 'sidekicks', base: '.sidekicks' };
  if (wanted === 'root') return [root];

  const projects = [];
  const projectsDir = join(repoRoot, 'projects');
  if (existsSync(projectsDir)) {
    let entries = [];
    try { entries = readdirSync(projectsDir, { withFileTypes: true }); } catch { entries = []; }
    for (const dirent of entries) {
      if (!dirent.isDirectory() && !dirent.isSymbolicLink()) continue;
      const base = join('projects', dirent.name);
      // A project is a project when it carries a manifest — the same definition the rest of the
      // CLI uses. A bare directory under projects/ is not a scope.
      if (!existsSync(join(repoRoot, base, 'manifest.yaml'))) continue;
      projects.push({ scope: dirent.name, base });
    }
  }

  if (wanted === 'all') return [root, ...projects];

  if (wanted === 'active') {
    const { projectName, projectRelPath } = resolveEffectiveScope(readSettings(repoRoot));
    if (!projectRelPath) return [root];
    return [{ scope: projectName, base: projectRelPath }];
  }

  const named = projects.find((p) => p.scope === wanted);
  if (!named) {
    throw new SidekicksError(
      `config sync: no project '${wanted}' — pass 'active', 'root', 'all', or a project name `
      + `(${projects.map((p) => p.scope).join(', ') || 'none found'})`,
      EXIT_VALIDATION
    );
  }
  return [named];
}

